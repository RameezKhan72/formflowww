def ex(id, name, group, level, equipment, views, sets, reps, metric, thresholds, muscles, keyframes,
       rules=(), mode="reps", seconds=30, hold=None, tips=(), mistakes=(), camera=None, typ="bodyweight", status="beta"):
    d = {"id": id, "name": name, "group": group, "mode": mode, "level": level, "equipment": equipment,
         "views": views, "status": status, "type": typ,
         "defaults": {"sets": sets, "reps": reps, "seconds": seconds},
         "metric": metric, "thresholds": thresholds, "rules": list(rules), "muscles": muscles,
         "tips": list(tips), "mistakes": list(mistakes), "keyframes": keyframes}
    if hold: d["hold"] = hold
    if camera: d["cameraTip"] = camera
    return d

def rule(id, when, cue, severity="moderate", category="form", phase="moving", joints=(), view=None, bilateral=False, persist=4):
    r = {"id": id, "when": when, "cue": cue, "severity": severity, "category": category, "phase": phase,
         "joints": list(joints), "persistFrames": persist}
    if view: r["view"] = view
    if bilateral: r["bilateral"] = True
    return r

def shallow(cue, joints=()):
    return rule("shallow", {"depthReached": False}, cue, "moderate", "depth", "rep_end", joints)

